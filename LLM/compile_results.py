"""
LLM Benchmark Results Compiler

Collects LLM benchmark results from each device-specific benchmark folder,
extracts the averaged metrics, and combines them into a single CSV file.

Expected folder structure:

LLM/
-compile_results.py
-LLM_Bench_PC_CPU/
-LLM_Bench_PC_GPU/
-LLM_Bench_RPi5/
-LLM_Bench_Android/

Each benchmark CSV contains the individual benchmark runs and an
avg_metrics column containing the averaged results for the three runs.
"""

import csv
import os
import re

# Main LLM benchmark directory.
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# Device folders containing the benchmark CSV files.
BENCHMARK_FOLDERS = [
    "LLM_Bench_PC_CPU",
    "LLM_Bench_PC_GPU",
    "LLM_Bench_Pi5",
    "LLM_Bench_Android",
]

# Output file for the combined results.
OUTPUT_FILE = os.path.join(
    BASE_DIR,
    "LLM_Bench_Results.csv"
)

# Extract the averaged benchmark metrics from the avg_metrics column.
def parse_avg_metrics(avg_metrics):

    metrics = {
        "avg_total_duration_s": None,
        "avg_load_duration_s": None,
        "avg_prompt_eval_count": None,
        "avg_prompt_eval_duration_s": None,
        "avg_prompt_eval_rate_tokens_s": None,
        "avg_eval_count": None,
        "avg_eval_duration_s": None,
        "avg_eval_rate_tokens_s": None,
        "avg_carbon_emissions_kgCO2e": None,
    }

    # Match each metric and its value from the avg_metrics text.
    patterns = {
        "avg_total_duration_s": r"Avg Total Duration:\s*([\d.]+)s",

        "avg_load_duration_s": r"Avg Load Duration:\s*([\d.]+)s",

        "avg_prompt_eval_count": r"Avg Prompt Eval Count:\s*([\d.]+)",

        "avg_prompt_eval_duration_s": r"Avg Prompt Eval Duration:\s*([\d.]+)s",

        "avg_prompt_eval_rate_tokens_s": r"Avg Prompt Eval Rate:\s*([\d.]+)\s*tokens/s",

        "avg_eval_count": r"Avg Eval Count:\s*([\d.]+)",

        "avg_eval_duration_s": r"Avg Eval Duration:\s*([\d.]+)s",

        "avg_eval_rate_tokens_s": r"Avg Eval Rate:\s*([\d.]+)\s*tokens/s",

        "avg_carbon_emissions_kgCO2e": r"Avg Carbon Emissions:\s*([\d.eE+-]+)\s*kgCO2e",
    }

    # Keep the values as strings so the carbon emissions remain in scientific notation.
    for metric_name, pattern in patterns.items():
        match = re.search(pattern, avg_metrics)

        if match:
            metrics[metric_name] = match.group(1)

    return metrics

# Read one benchmark CSV and extract its results.
def process_csv(csv_path):

    results = []

    with open(
        csv_path,
        "r",
        encoding="utf-8-sig",
        newline=""
    ) as file:

        reader = csv.DictReader(file)

        # Check that the CSV has the columns used by the compiler.
        required_columns = {
            "device_name",
            "model_name",
            "workload_category",
            "avg_metrics",
        }

        missing_columns = required_columns - set(reader.fieldnames or [])

        # Skip files that do not match the expected LLM benchmark format.
        if missing_columns:
            print(
                f"WARNING: Skipping {csv_path} - "
                f"missing columns: {', '.join(missing_columns)}"
            )
            return results

        for row in reader:

            # Extract the averaged metrics generated by the benchmark.
            avg_metrics = row.get("avg_metrics", "")

            parsed_metrics = parse_avg_metrics(
                avg_metrics
            )

            # Store the results using names that are easier to use when creating tables and graphs.
            result = {
                "Device": row["device_name"],
                "Model": row["model_name"],
                "Workload Category": row["workload_category"],
                "Average Total Duration (s)": parsed_metrics["avg_total_duration_s"],
                "Average Load Duration (s)": parsed_metrics["avg_load_duration_s"],
                "Average Prompt Evaluation Count": parsed_metrics["avg_prompt_eval_count"],
                "Average Prompt Evaluation Duration (s)": parsed_metrics["avg_prompt_eval_duration_s"],
                "Average Prompt Evaluation Rate (tokens/s)": parsed_metrics["avg_prompt_eval_rate_tokens_s"],
                "Average Evaluation Count": parsed_metrics["avg_eval_count"],
                "Average Evaluation Duration (s)": parsed_metrics["avg_eval_duration_s"],
                "Average Evaluation Rate (tokens/s)": parsed_metrics["avg_eval_rate_tokens_s"],
                "Average Carbon Emissions (kgCO2e)": parsed_metrics["avg_carbon_emissions_kgCO2e"],
            }

            results.append(result)

    return results


def main():

    print("\n" + "=" * 70)
    print("LLM Benchmark Results Compiler")
    print("=" * 70)

    all_results = []
    files_processed = 0

    # Search each device folder for benchmark CSV files.
    for folder_name in BENCHMARK_FOLDERS:

        folder_path = os.path.join(
            BASE_DIR,
            folder_name
        )

        # Continue with the remaining devices if a benchmark folder has not been created or is not present.
        if not os.path.isdir(folder_path):
            print(
                f"\nWARNING: Folder not found: {folder_name}"
            )
            continue

        print(f"\nScanning: {folder_name}")

        # Find all CSV files in the current device benchmark folder.
        csv_files = [
            file_name
            for file_name in os.listdir(folder_path)
            if file_name.lower().endswith(".csv")
            and file_name.lower() != "emissions.csv"
        ]

        if not csv_files:
            print("  No CSV files found.")
            continue

        # Process every benchmark CSV found for the current device.
        for file_name in sorted(csv_files):

            csv_path = os.path.join(
                folder_path,
                file_name
            )

            print(f"  Processing: {file_name}")

            results = process_csv(csv_path)

            all_results.extend(results)
            files_processed += 1

            print(
                f"    Results extracted: {len(results)}"
            )

    # Do not create an empty output file if no valid benchmark results were found.
    if not all_results:
        print("\nNo benchmark results were found.")
        return

    # Define the column names for the final results CSV.
    fieldnames = [
        "Device",
        "Model",
        "Workload Category",
        "Average Total Duration (s)",
        "Average Load Duration (s)",
        "Average Prompt Evaluation Count",
        "Average Prompt Evaluation Duration (s)",
        "Average Prompt Evaluation Rate (tokens/s)",
        "Average Evaluation Count",
        "Average Evaluation Duration (s)",
        "Average Evaluation Rate (tokens/s)",
        "Average Carbon Emissions (kgCO2e)",
    ]

    # Write the compiled results to the output CSV.
    with open(
        OUTPUT_FILE,
        "w",
        encoding="utf-8",
        newline=""
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writeheader()
        writer.writerows(all_results)

    print("\n" + "=" * 70)
    print("Compilation complete")
    print("=" * 70)

    print(f"CSV files processed: {files_processed}")
    print(f"Benchmark results: {len(all_results)}")
    print(f"Output file: {OUTPUT_FILE}")

    print( "="  * 70 + "\n")


if __name__ == "__main__":
    main()